# Logical operators are used to combine conditions
# They work with True / False

# three types 
# and , or , not

"""

and operator
it will print true if both conditions are true else will print false  
 
"""

x = 18
print ( x > 5 and x < 20 ) # it will print true else 
print ( x >= 18 and x < 18 ) # it will print false 


"""

 or operator 
 it will print true if on condition is true else will print false 
 
 """
 
w = 7
print ( w > 5 or w == 10 ) # it will print true because one conditions is true 
print ( w < 5 or w > 10 ) # it will print false because both conditions are false 


"""

not operator 
it reverse the result 

"""

s = 35
print( not s > 90 ) # it will print true 
print( not s < 40 ) # it will print false 


# example 

v = 10

print(not v == 10) # it will print false 
print(not v != 5)  # it will print false 
