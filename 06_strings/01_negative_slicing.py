name = "Harry"

print(name[0:3])

print(name[-4: -1])
print(name[1:4])

print(name[:4]) # is same as print(name[0:4])
print(name[1:]) # is same as print(name[1:5])
print(name[1:5])

# negative slicing

name1 = "shalmani"
print(name1[1:5]) 
print(name1[-7:-3]) # it also mean (name1[1:5])  
# fisrt index will be included like 1 or -7 in the above example and last index will be excluded like 5 or -3



