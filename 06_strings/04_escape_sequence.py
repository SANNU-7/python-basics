# Escape sequence characters are special characters used inside strings, starting with \, to do special work.

"""
\n → new line

\t → tab (space)

\' → single quote

\" → double quote

\\ → backslash

"""
print("my name is \"Sanan Shah\"\nbut you can call me \"Sanny\" ")

# what if this line is print in single quote 

print('my name is \"Sanan Shah\"\nbut you can call me \'Sanny\' ')